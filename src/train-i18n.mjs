export function translate(key, values = {}, language = 'zh') {
  const text = language === 'en' ? (EN[key] ?? key) : key;
  return text.replace(/\{(\w+)\}/g, (whole, name) => String(values[name] ?? whole));
}
export function localisePanel(root, language) {
  for (const element of root.querySelectorAll('[data-train-t]')) {
    element.textContent = translate(element.dataset.trainT, {}, language);
  }
  for (const attr of ['aria-label', 'placeholder']) {
    for (const element of root.querySelectorAll(`[data-train-${attr}]`)) {
      element.setAttribute(attr, translate(element.getAttribute(`data-train-${attr}`), {}, language));
    }
  }
}
